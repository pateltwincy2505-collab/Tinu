export function getProductImage(productId: string, subCategory: string, name: string): string {
  if (PRODUCT_IMAGE_MAP[productId]) {
    return PRODUCT_IMAGE_MAP[productId];
  }
  const n = name.toLowerCase();
  const sub = subCategory.toLowerCase();

  if (sub.includes('caliper')) return calDigitalCaliper;
  if (sub.includes('micrometer')) return calDigitalMicrometer;
  if (sub.includes('multimeter')) return calMultimeterTrms;
  if (sub.includes('clamp')) return calClampMeter;
  return calVernierCaliper;
}

